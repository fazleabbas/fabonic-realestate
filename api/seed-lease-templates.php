<?php
/**
 * Fabonic Real Estate — Lease Template Seeder
 * ------------------------------------------------------------
 * Installs the built-in lease templates (includes/lease_templates_seed.php)
 * into tenant databases.
 *
 * New tenants get these from sql/tenant_schema.sql at provisioning time.
 * This script is for tenants that already exist.
 *
 * Like run-tenant-crons.php, it runs in two modes, because the master does NOT
 * know each tenant's DB password (those live only in the tenant's own config):
 *
 *   MASTER MODE   (config defines RE_TENANTS_PATH — i.e. public_html)
 *       Lists tenants from the central DB and executes each tenant's OWN copy
 *       of this script with --self, so it connects with that tenant's config.
 *
 *   SELF MODE     (--self, or a config with no RE_TENANTS_PATH — a tenant copy)
 *       Seeds the database this instance is configured for.
 *
 * SAFE TO RE-RUN. A template is inserted only if no template with the same
 * name already exists, and the default flag is set only when the tenant has no
 * default template yet — an existing tenant's own templates are never touched.
 *
 * Usage (from the master):
 *   php /home/realcotz/public_html/api/seed-lease-templates.php
 *   php .../seed-lease-templates.php --slug=acme      # one tenant only
 *   php .../seed-lease-templates.php --dry-run        # report, change nothing
 *   php .../seed-lease-templates.php --emit-sql       # print the tenant_schema.sql block
 *
 * Or via browser (guarded):
 *   https://real.co.tz/api/seed-lease-templates.php?key=<SEED_LEASE_TEMPLATES_KEY>
 */

$isCli = (php_sapi_name() === 'cli');

// ---- Arguments (CLI flags, or query string on the web) -------------------
$argvList  = $isCli ? array_slice($_SERVER['argv'] ?? [], 1) : [];
$hasFlag   = function (string $flag) use ($isCli, $argvList) {
    return $isCli ? in_array('--' . $flag, $argvList, true) : isset($_GET[$flag]);
};
$flagValue = function (string $flag) use ($isCli, $argvList) {
    if (!$isCli) {
        return trim((string)($_GET[$flag] ?? ''));
    }
    foreach ($argvList as $arg) {
        if (strpos($arg, '--' . $flag . '=') === 0) {
            return substr($arg, strlen($flag) + 3);
        }
    }
    return '';
};

$selfMode = $hasFlag('self');
$dryRun   = $hasFlag('dry-run');
$emitSql  = $hasFlag('emit-sql');
$onlySlug = $flagValue('slug');

require_once __DIR__ . '/../includes/lease_templates_seed.php';

if (!$isCli) {
    require_once __DIR__ . '/../includes/secrets.php';
    if (!appSecretMatches('SEED_LEASE_TEMPLATES_KEY', $_GET['key'] ?? null)) {
        http_response_code(403);
        die('Access denied');
    }
    header('Content-Type: text/plain; charset=utf-8');
}

function sltLog(string $msg): void
{
    $line = '[' . date('Y-m-d H:i:s') . "] {$msg}\n";
    echo $line;
    @error_log($line, 3, __DIR__ . '/seed-lease-templates.log');
    @flush();
}

// =========================================================================
// --emit-sql : regenerate the INSERT block for sql/tenant_schema.sql
// =========================================================================
if ($emitSql) {
    if (!$isCli) {
        header('Content-Type: text/plain; charset=utf-8');
    }
    $rows = [];
    foreach (leaseTemplateSeedData() as $tpl) {
        $rows[] = "('" . str_replace("'", "\\'", $tpl['name']) . "',\n'"
            . str_replace(["\\", "'"], ["\\\\", "\\'"], $tpl['content']) . "',\n"
            . (int)$tpl['is_default'] . ")";
    }
    echo "-- Built-in lease templates (generated by api/seed-lease-templates.php --emit-sql)\n";
    echo "-- Edit includes/lease_templates_seed.php and regenerate; do not hand-edit.\n";
    echo "INSERT INTO `lease_templates` (`name`, `content`, `is_default`) VALUES\n";
    echo implode(",\n", $rows) . ";\n";
    exit(0);
}

// Everything below needs a database.
require_once __DIR__ . '/../config/database.php';

// =========================================================================
// SELF MODE — seed the database this instance is configured for
// =========================================================================
if ($selfMode || !defined('RE_TENANTS_PATH')) {
    $label = defined('TENANT_SLUG') ? TENANT_SLUG : 'local';

    try {
        $conn->query("SELECT 1 FROM lease_templates LIMIT 1");
    } catch (PDOException $e) {
        sltLog("ERROR [{$label}]: lease_templates table not found — is this a tenant database?");
        exit(1);
    }

    $existing = $conn->query("SELECT LOWER(name) FROM lease_templates")->fetchAll(PDO::FETCH_COLUMN);
    $existing = array_flip($existing);
    $hasDefault = (int)$conn->query("SELECT COUNT(*) FROM lease_templates WHERE is_default = 1")->fetchColumn() > 0;

    $inserted = 0;
    $skipped  = 0;

    $insert = $conn->prepare(
        "INSERT INTO lease_templates (name, content, is_default) VALUES (:name, :content, :is_default)"
    );

    foreach (leaseTemplateSeedData() as $tpl) {
        if (isset($existing[strtolower($tpl['name'])])) {
            $skipped++;
            continue;
        }

        // Never steal the default flag from a template the tenant already chose.
        $isDefault = ($tpl['is_default'] && !$hasDefault) ? 1 : 0;

        if (!$dryRun) {
            $insert->execute([
                'name'       => $tpl['name'],
                'content'    => $tpl['content'],
                'is_default' => $isDefault,
            ]);
        }
        if ($isDefault) {
            $hasDefault = true;
        }
        $inserted++;
    }

    $prefix = $dryRun ? 'DRY-RUN ' : '';
    sltLog("{$prefix}[{$label}] inserted={$inserted} skipped_existing={$skipped}");
    exit(0);
}

// =========================================================================
// MASTER MODE — fan out to every tenant
// =========================================================================
sltLog('=== LEASE TEMPLATE SEED START ===');

try {
    $central = new PDO(
        'mysql:host=' . DB_HOST . ';dbname=' . CENTRAL_DB_NAME . ';charset=utf8mb4',
        defined('CENTRAL_DB_USER') ? CENTRAL_DB_USER : DB_USER,
        defined('CENTRAL_DB_PASS') ? CENTRAL_DB_PASS : DB_PASS,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
    );
    $stmt = $central->query(
        "SELECT tenant_slug FROM subscriptions WHERE status IN ('trial','active') ORDER BY tenant_slug"
    );
    $tenants = $stmt->fetchAll(PDO::FETCH_COLUMN);
} catch (PDOException $e) {
    sltLog('ERROR: cannot read central DB: ' . $e->getMessage());
    exit(1);
}

if ($onlySlug !== '') {
    $tenants = array_values(array_filter($tenants, function ($s) use ($onlySlug) {
        return $s === $onlySlug;
    }));
    if (!$tenants) {
        sltLog("ERROR: tenant '{$onlySlug}' not found among active tenants");
        exit(1);
    }
}

sltLog('Tenants to seed: ' . count($tenants) . ($dryRun ? ' (DRY RUN)' : ''));

$php     = PHP_BINARY ?: 'php';
$done    = 0;
$skipped = 0;

foreach ($tenants as $slug) {
    $script = RE_TENANTS_PATH . '/' . $slug . '/api/seed-lease-templates.php';
    if (!is_file($script)) {
        sltLog("  SKIP {$slug}: seeder not present in tenant folder (copy this file across first)");
        $skipped++;
        continue;
    }

    $cmd = escapeshellarg($php) . ' ' . escapeshellarg($script) . ' --self';
    if ($dryRun) {
        $cmd .= ' --dry-run';
    }

    $out = [];
    $rc  = 0;
    exec($cmd . ' 2>&1', $out, $rc);
    $tail = count($out) ? ' | ' . trim(implode(' ', array_slice($out, -1))) : '';
    sltLog("  {$slug}: exit={$rc}{$tail}");
    $done++;
}

sltLog("=== DONE: {$done} tenants seeded, {$skipped} skipped ===");
